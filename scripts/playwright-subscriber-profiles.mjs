import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'
import {staticBrowser,staticBase} from './static-browser.mjs'
import {PROFILES} from '../src/pages/dca-profiles/data.js'
import {prepareProfile} from '../src/pages/dca-profiles/engine.js'
const output='test-artifacts/subscriber-profiles'
await mkdir(output,{recursive:true})
for(const width of [1440,390,320]){
 const {browser,page}=await staticBrowser(width),errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 try{
  await page.goto(staticBase)
  const prepared={id:'prepared-save',title:'Scénario',profile:prepareProfile(PROFILES[0]),draft:'',field:'all'}
  const legacy={...prepared,id:'legacy-subscriber',title:'Profil reçu autrefois',profile:{...prepared.profile,mode:'participant'},draft:'Texte personnel historique'}
  await page.evaluate(({prepared,legacy})=>{
   localStorage.clear()
   localStorage.setItem('el-dca-portfolios-v2',JSON.stringify({version:2,items:[prepared,{...prepared,id:'anonymous',profile:{...prepared.profile,imageOnly:true}},legacy]}))
   localStorage.setItem('el-dca-used-v1',JSON.stringify(['julien']))
  },{prepared,legacy})
  await page.goto(staticBase+'le-dca-de?mode=subscribers')
  const library=page.getByRole('region',{name:'Profils d’abonnés enregistrés',exact:true})
  await library.getByRole('button',{name:'Ajouter un profil d’abonné',exact:true}).waitFor()
  assert.equal(await library.locator('article').count(),1)
  assert.equal(await page.locator('#dca-compose').count(),0,'A prepared scenario must not masquerade as an incoming subscriber')
  await library.getByRole('button',{name:'Ajouter un profil d’abonné',exact:true}).click()
  const name=page.getByLabel('Pseudonyme',{exact:true})
  assert.equal(await name.inputValue(),'')
  assert.equal(await page.locator('.dca-position').count(),0)
  await name.fill('Élodie')
  assert(await library.getByRole('button',{name:'Enregistrer ce profil',exact:true}).isDisabled())
  await page.getByRole('button',{name:'Ajouter un placement manuellement',exact:true}).click()
  const form=page.locator('.dca-manual-form')
  await form.getByLabel('Nom du placement',{exact:true}).fill('Fonds euros Mutavie')
  await form.getByLabel('Catégorie',{exact:true}).selectOption('Fonds en euros')
  await form.getByLabel('Versement mensuel',{exact:false}).fill('100')
  await form.getByRole('button',{name:'Ajouter ce placement',exact:true}).click()
  const custom='Profil reçu — texte à conserver exactement.'
  await page.locator('#dca-draft').fill(custom)
  await library.getByRole('button',{name:'Enregistrer ce profil',exact:true}).click()
  await library.getByText(/Profil enregistré sur cet appareil/).waitFor()
  await page.locator('.dca-simple-preview img').filter({visible:true}).evaluate(async img=>img.decode())
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('el-dca-portfolios-v2')).items)
  const first=saved.find(item=>item.title==='Élodie')
  assert.match(first.profile.id,/^subscriber:/);assert.notEqual(first.profile.id,'julien')
  assert.equal(first.profile.lines[0].isin,'');assert.equal(first.draft,custom)
  await page.getByText('Présentation facultative',{exact:true}).click()
  await page.getByLabel('Activité',{exact:true}).fill('Infirmière')
  await library.getByRole('button',{name:'Ajouter un profil d’abonné',exact:true}).click()
  const pending=library.getByRole('group',{name:'Modifications du profil en cours',exact:true})
  await pending.getByRole('button',{name:'Annuler',exact:true}).click()
  assert.equal(await name.inputValue(),'Élodie')
  await library.getByRole('button',{name:'Ajouter un profil d’abonné',exact:true}).click()
  await pending.getByRole('button',{name:'Enregistrer puis continuer',exact:true}).click()
  assert.equal(await name.inputValue(),'')
  await name.fill('Élodie')
  const picker=page.getByRole('group',{name:'Ajouter un actif',exact:true})
  await picker.getByRole('searchbox').fill('Livret A')
  await picker.locator('[data-option][data-value="livret-a"]').click()
  await library.getByRole('button',{name:'Enregistrer ce profil',exact:true}).click()
  await page.reload()
  await library.getByRole('button',{name:'Mettre à jour ce profil',exact:true}).waitFor()
  assert.equal(await library.locator('article').count(),3)
  const all=await page.evaluate(()=>JSON.parse(localStorage.getItem('el-dca-portfolios-v2')).items)
  const matching=all.filter(item=>item.title==='Élodie')
  assert.equal(matching.length,2);assert.notEqual(matching[0].profile.id,matching[1].profile.id)
  await library.getByLabel('Rechercher un profil',{exact:true}).fill('infirmiere')
  assert.equal(await library.locator('article').count(),1)
  await library.getByRole('button',{name:'Ouvrir Élodie',exact:true}).click()
  assert.equal(await page.locator('#dca-draft').inputValue(),custom)
  assert.equal(await page.getByRole('checkbox',{name:'La personne a validé',exact:false}).isChecked(),false)
  await name.fill('Élodie — profil actualisé')
  await library.getByRole('button',{name:'Mettre à jour ce profil',exact:true}).click()
  const updated=await page.evaluate(id=>JSON.parse(localStorage.getItem('el-dca-portfolios-v2')).items.find(item=>item.id===id),first.id)
  assert.equal(updated.profile.id,first.profile.id);assert.equal(updated.profile.name,'Élodie — profil actualisé')
  await library.getByRole('button',{name:'Marquer publié',exact:true}).click()
  assert((await library.innerText()).includes('Déjà publié'))
  await page.getByRole('button',{name:'Le DCA d’un abonné',exact:true}).click()
  assert.equal(await name.inputValue(),'Élodie — profil actualisé')
  await page.getByRole('button',{name:'Profils d’abonnés',exact:true}).click()
  await library.getByLabel('Rechercher un profil',{exact:true}).fill('')
  await library.getByRole('button',{name:'Ouvrir Profil reçu autrefois',exact:true}).click()
  assert.equal(await page.locator('#dca-draft').inputValue(),legacy.draft)
  await library.getByRole('button',{name:'Supprimer Profil reçu autrefois',exact:true}).click()
  assert.equal(await library.getByRole('button',{name:'Ouvrir Profil reçu autrefois',exact:true}).count(),0)
  assert.equal(await name.inputValue(),legacy.profile.name,'Deleting a saved item keeps the open draft')
  await library.getByRole('button',{name:'Ouvrir Élodie — profil actualisé',exact:true}).click()
  await pending.getByRole('button',{name:'Continuer sans enregistrer',exact:true}).click()
  // A concurrent edit must not be overwritten by this editor's stale snapshot.
  await page.evaluate(id=>{
   const raw=JSON.parse(localStorage.getItem('el-dca-portfolios-v2'))
   raw.items.find(item=>item.id===id).draft='Modifié dans un autre onglet'
   localStorage.setItem('el-dca-portfolios-v2',JSON.stringify(raw))
   window.dispatchEvent(new StorageEvent('storage',{key:'el-dca-portfolios-v2'}))
  },first.id)
  await name.fill('Élodie — ma modification locale')
  await library.getByRole('button',{name:'Mettre à jour ce profil',exact:true}).click()
  await library.getByRole('alert').filter({hasText:'autre onglet'}).waitFor()
  assert.equal(await page.evaluate(id=>JSON.parse(localStorage.getItem('el-dca-portfolios-v2')).items.find(item=>item.id===id).draft,first.id),'Modifié dans un autre onglet')
  assert.equal(await name.inputValue(),'Élodie — ma modification locale')
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  await page.locator('.dca-simple-preview img').filter({visible:true}).evaluate(async img=>img.decode())
  await page.screenshot({path:`${output}/profiles-${width}.png`,fullPage:true})
  assert.deepEqual(errors,[])
  await page.evaluate(()=>{localStorage.setItem('el-dca-portfolios-v2','corrompu');window.dispatchEvent(new StorageEvent('storage',{key:'el-dca-portfolios-v2'}))})
  await library.getByRole('alert').filter({hasText:'ne peuvent pas être lues'}).waitFor()
  await library.getByRole('button',{name:'Mettre à jour ce profil',exact:true}).click()
  assert.equal(await page.evaluate(()=>localStorage.getItem('el-dca-portfolios-v2')),'corrompu')
 }finally{await browser.close()}
}
console.log('Profils abonnés : parcours dédiés à 1440/390/320 px, saisie, doublons de noms, sauvegarde/reprise/mise à jour, textes, historique, héritage, suppression et conflits vérifiés.')
