import assert from 'node:assert/strict'
import {FLOW_SOURCES,parsePastedFlows} from '../src/pages/etf-flows/paste.js'
assert.deepEqual(FLOW_SOURCES.map(s=>new URL(s.url).hostname),['etfexpress.com'])
const signed=parsePastedFlows('US exposures : +3,82 Md€\nEurope : +772,7 M€\nChina : −164,9 M€','geography')
assert.deepEqual(signed.warnings,[])
assert.deepEqual(signed.rows.map(r=>r.amount),[3820000000,772700000,-164900000])
assert.equal(signed.currency,'EUR')
const english=parsePastedFlows('Financials ETFs recorded the largest sector inflow at €421.7 million.\nIndustrials (€79.4 million), Real Estate (€61.1 million), and Consumer Discretionary (€9.9 million) recorded the largest sector outflows.','sector')
assert.deepEqual(english.warnings,[])
assert.deepEqual(english.rows.map(r=>[r.label,r.amount]),[['Financials',421700000],['Industrials',-79400000],['Real Estate',-61100000],['Consumer Discretionary',-9900000]])
const cards=parsePastedFlows('Health Care\n+$733M\nReal Estate\n+$544M','sector')
assert.deepEqual(cards.warnings,[])
assert.deepEqual(cards.rows.map(r=>[r.label,r.amount]),[['Health Care',733000000],['Real Estate',544000000]])
for (const bad of ['Tech : 5 M€','Tech : +5%','YTD flows +$2B','Global AuM +$22B','Tech +€1,234.5M','Tech +€2M outflows','Tech attracted €2M while Europe lost €1M','Europe : +1 M€\nEurope : +2 M€','Europe : +1 M€\nChina : +2 M$']) assert(parsePastedFlows(bad,'sector').warnings.length,bad)
assert.throws(()=>parsePastedFlows('A : +1 M€','invalid'))
assert.throws(()=>parsePastedFlows('A'.repeat(50001),'sector'))
assert.equal(parsePastedFlows('A : +0 €','sector').rows[0].amount,0)
assert.equal(parsePastedFlows('A : +4 €','sector').rows[0].amount,4)
assert.equal(parsePastedFlows('S&P 500\n+$12M','geography').rows[0].label,'S&P 500')
assert.equal(parsePastedFlows('A : +'+ '9'.repeat(400)+' M€','sector').rows.length,0)
assert.equal(parsePastedFlows('Net assets : +5 M€','sector').rows.length,0)
console.log('ETF paste import: real dated excerpts, signed cards, units, negative flows, duplicates and unsafe input passed.')

await import('./test-etf-express-report.mjs')
