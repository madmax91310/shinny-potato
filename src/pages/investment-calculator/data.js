// Chaque actif a une liste de points {date:"AAAA-MM", price: nombre}.
// Les prix entre deux points sont interpolés linéairement.
// Repris tel quel de la session d'origine, aucune donnée modifiée.
function P(list) {
  const out = []
  for (let i = 0; i < list.length; i += 2) out.push({ date: list[i], price: list[i + 1] })
  return out
}

